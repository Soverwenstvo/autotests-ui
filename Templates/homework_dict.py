# ============================================================================
# ЗАДАНИЕ 1: Обновление цены товара
# ============================================================================
# В словаре лежат цены товаров по SKU.
# Если SKU есть — обновите цену.
# Если SKU нет — добавьте новую пару ключ-значение.

prices = {
    1010: 249.90,
    1012: 319.00,
    1015: 199.50,
}
sku_to_update = 1012
new_price = 299.00

# Ваш код здесь:

if sku_to_update in prices:
    prices[sku_to_update] = new_price

print(prices)

# ============================================================================
# ЗАДАНИЕ 2: Подсчет заказов по менеджерам
# ============================================================================
# Даны менеджеры, каждый элемент — имя менеджера.
# Нужно собрать словарь: имя -> количество заказов (количество заказов придумайте сами).

managers = ["Иван", "Ольга", "Иван", "Дмитрий", "Ольга", "Иван"]
orders = [100,1332,3343,545,556,69]
# Ваш код здесь:

managers_dict = {}

for manager, count in zip(managers, orders):
    managers_dict[manager] = managers_dict.get(manager, 0) + count

print(managers_dict)


