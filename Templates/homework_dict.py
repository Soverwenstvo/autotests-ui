# ЗАДАНИЕ 4: Товары с остатком ниже порога
# ============================================================================
# В словаре: SKU -> остаток.
# Нужно собрать новый словарь только с товарами,где остаток меньше min_level.

stock = {
    1010: 12,
    1012: 4,
    1015: 0,
    1020: 9
}
min_level = 5

# Ваш код здесь:
stock_dict = {}
for sku, amount in stock.items():
    if amount < min_level:
        stock_dict[sku] = amount
print(stock_dict)
