# ЗАДАНИЕ 3: Итог по заказу с объемной скидкой
# ============================================================================
# Скидка зависит от количества:
# 0-9: 0%
# 10-49: 5%
# 50-99: 10%
# 100+: 15%
#
# Посчитать итоговую сумму с учетом скидки.

quantity = -1
price_per_unit = 299.90

# Ваш код здесь:

if 0 <= quantity <= 9:
    discount_rate = 0
elif 10 <= quantity <= 49:
    discount_rate = 0.5
elif 50 <= quantity <= 99:
    discount_rate = 0.10
else:
    discount_rate = 0.15
total_price = quantity * price_per_unit * (1 - discount_rate)
print(total_price)

# ============================================================================
# ЗАДАНИЕ 4: Округление счета до шага
# ============================================================================
# Счет нужно округлить вверх до ближайшего кратного шагу (например, до 50).
# Пример: 142 -> 150, 150 -> 150.

bill_amount = 142.0
step = 50

# Ваш код здесь:
rounded = round(bill_amount / step) * step
print(rounded)
# ============================================================================
# ЗАДАНИЕ 5: Зарплата с переработкой
# ============================================================================
# Базовая норма часов в месяц = 160.
# Все часы сверх нормы оплачиваются с коэффициентом 1.5.
# Нужно посчитать итоговую зарплату.

hours_worked = 172
hourly_rate = 450.0

# Ваш код здесь:
base_hours = min(hours_worked, 160)
overtime_hours = max(0, hours_worked - 160)

salary = (base_hours * hourly_rate) + \
         (overtime_hours * hourly_rate * 1.5)
print(salary)

