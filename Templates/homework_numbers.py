amount = 12500.0
min_amount = 100.0
max_amount = 50000.0

# Ваш код здесь:

if min_amount <= amount <= max_amount:
    print("OK")
else:
    print("ERROR")
# ============================================================================
# ЗАДАНИЕ 2: Расчет НДС и цены без НДС
# ============================================================================
# Цена указана с НДС. Нужно найти:
# - цену без НДС
# - сумму НДС

price_with_vat = 11800.0
vat_rate = 0.22

# Ваш код здесь:
price_no_vat = price_with_vat / (1 + vat_rate)  # Цена без НДС
nds = price_with_vat - price_no_vat  # Сумма НДС
print(round(price_no_vat, 2))  # 9672.13
print(round(nds, 2))  # 2127.87
